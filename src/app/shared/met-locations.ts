const KANTO_FIRST = 0x58;

export function metLocationName(id: number): string {
  if (id === 0xfe) return 'In-game trade';
  if (id === 0xff) return 'Gift';
  return KANTO[id - KANTO_FIRST] ?? `Location #${id}`;
}

